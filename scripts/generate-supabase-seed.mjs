// Regenerates supabase/seed.sql from the backend dataset so the two never drift.
// The dataset (Test_AI_Agent_Upload/Data/madrasati-dataset.json) is the single source of truth for the demo.
//   node scripts/generate-supabase-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dataset = JSON.parse(readFileSync("Test_AI_Agent_Upload/Data/madrasati-dataset.json", "utf8"));
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;

const rows = dataset.students
  .map((s) => `  (${[s.id, s.name, s.firstName, s.grade, s.school].map(sql).join(", ")})`)
  .join(",\n");

writeFileSync(
  "supabase/seed.sql",
  `-- GENERATED by scripts/generate-supabase-seed.mjs from Test_AI_Agent_Upload/Data/madrasati-dataset.json. Do not edit by hand.
-- Fictional students only. No parent profiles, Auth users or links: an administrator links test accounts
-- explicitly with supabase/admin/link-test-parent.sql.
insert into public.students (demo_key, full_name, first_name, grade_label, school_name) values
${rows}
on conflict (demo_key) do nothing;
`,
);
console.log(`Wrote supabase/seed.sql with ${dataset.students.length} students`);
